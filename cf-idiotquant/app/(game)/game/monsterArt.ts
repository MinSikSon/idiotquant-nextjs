/** 그 종의 얼굴. 없으면 null — 화면이 그 자리를 비워 둔다. */
export function monsterArt(ch: string): string | null {
    const a = ART[ch];
    // 소스에서 읽기 좋으라고 앞뒤에 줄바꿈을 두었다. 그릴 때는 뗀다.
    //
    // **닫는 backtick 은 반드시 다음 줄에 둔다.** 그림의 마지막 줄이 `\` 로 끝나는
    // 종이 여럿인데(트롤·용·오크 …), 같은 줄에 두면 그 역슬래시가 backtick 을
    // 이스케이프해서 템플릿이 안 닫힌다. 실제로 그렇게 터졌다.
    return a ? a.replace(/^\n/, "").replace(/\n$/, "") : null;
}

/** 그림이 있는 글자들 — 테스트가 스물여섯을 다 세는 데 쓴다. */
export const ART_LETTERS = Object.keys(ART);

/** 제일 긴 줄의 칸 수. 폰에서 안 접히는지 재는 데 쓴다. */
export function artWidth(ch: string): number {
    const a = monsterArt(ch);
    if (!a) return 0;
    return Math.max(...a.split("\n").map((l) => l.length));
}
