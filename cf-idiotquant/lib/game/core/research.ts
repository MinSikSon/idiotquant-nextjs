// 알아본다 — **근거를 만드는 단 하나의 행동.**
//
// ── 왜 이 파일이 생겼나 ────────────────────────────────────────
// 근거는 원래 **정보 카드**에서 나왔다. 손패 셋 중 정보 갈래를 내면 그 턴의 매수에
// 근거가 붙고 국면이 보였다. 카드를 걷어 내면서 그 출처가 통째로 사라졌는데, 근거가
// 없으면 이 게임의 규칙 절반이 죽는다 — 「결과 × 근거」 4분면에서 근거 있는 칸에
// 아무도 못 들어가고, 에너지는 오르기만 안 하고 줄기만 한다.
//
// 그래서 근거를 **카드가 아니라 행동**으로 옮겼다. 시세판에서 종목 하나를 골라
// 「알아본다」를 누르면 에너지를 쓰고 그 종목의 국면이 열리며, 그 턴 그 종목을 권할 때
// 근거가 된다. 하는 일은 정보 카드와 똑같고, 손패라는 층이 없어졌을 뿐이다.
//
// ── 규칙은 셋이다 ──────────────────────────────────────────────
//   한 턴에 한 종목        고객이 한 명이니 권하는 것도 하나다. 알아보는 것도 하나다.
//   알아본 그 종목만       다른 종목을 권하면 근거 없이 권한 것이다.
//   공짜가 아니다          `RESEARCH_COST` 만큼 에너지가 든다.
//
// 카드의 나머지 갈래(집행·방어·저주)는 같이 사라졌다. 손절·헤지·수수료 면제는 전부
// 카드 효과였다. 지금 `TurnBuff` 는 근거와 국면 두 가지만 채워져서 나간다 —
// **판의 뼈대를 세우는 동안에는 이 둘이면 된다.**

import { NO_BUFF, type TurnBuff } from "./types";

/** 한 종목을 알아보는 데 드는 에너지. 정보 카드가 들던 값과 같다. */
export const RESEARCH_COST = 3;

/**
 * 알아보면 국면이 **몇 겹까지** 열리는가.
 *
 * 2 면 「지금 국면 + 턴당 평균 등락 + 몇 턴 남았는가」까지다(`TurnBuff.regimeDepth`).
 * 1 은 "상승" 이라는 단어뿐이라 얼마를 걸지 못 정하고, 3 이상은 다음 국면까지 보여
 * 한 번 알아본 것으로 두 턴을 먹는다.
 */
export const RESEARCH_DEPTH = 2;

/**
 * 이번 턴의 상태를 엔진이 읽는 모양으로 만든다.
 *
 * @param researched 이번 턴 알아본 종목의 **이름**. 안 알아봤으면 null.
 *
 * 이름을 받는 이유: `thesis` 는 화면이 그대로 찍는 문구다(「근거 — 동방해운」).
 * 어느 종목인지는 씬이 id 로 따로 들고 있고, 여기 오는 것은 사람이 읽을 말이다.
 */
export function researchBuff(researched: string | null): TurnBuff {
    if (researched === null) return { ...NO_BUFF };
    return { ...NO_BUFF, thesis: researched, regimeDepth: RESEARCH_DEPTH };
}
