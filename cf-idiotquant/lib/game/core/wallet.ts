// 지갑 — **내 돈. 이 게임에 여태 없던 것.**
//
// ── 왜 생겼나 ────────────────────────────────────────────────
// 「IMF」의 돈은 셋이었다(`core/ledger.ts`) — 맡은 돈 · 얻은 돈 · 갚을 돈. 그런데 셋 중
// **내가 쥐고 있는 것이 하나도 없었다.** 맡은 돈은 고객 것이고, 보수는 받는 즉시 빚으로
// 직행했고, 빚은 애초에 내 것이 아니다. 그래서 이런 일이 벌어졌다.
//
//   · 1998년 1월에 이미 2,500만원짜리 계좌가 손에 쥐어져 있었다. 회사가 없어지고
//     명동 3층에 사무실 하나를 얻은 사람에게 **그 돈이 어디서 왔는지 아무도 안 말한다.**
//   · 보수를 받아도 화면에서 그냥 사라졌다. 빚 숫자만 줄었다. 번 적이 없는 셈이다.
//   · 그래서 「먹고사는 일」이 게임에 없었다. 12턴을 굶어도 아무 일도 안 일어난다.
//
// 지갑은 그 셋을 잇는다. **들어오는 길 둘, 나가는 길 둘.**
//
//     알바 ──┐                    ┌──▶ 생활비 (매 턴, 강제)
//            ├──▶ 【 지갑 】 ──────┤
//     보수 ──┘                    └──▶ 상환 (내가 누를 때만)
//
// ── 왜 상환이 자동이 아닌가 ──────────────────────────────────
// 예전에는 챕터가 끝나면 보수가 **곧장** 빚에서 깎였다. 편했지만 결정이 없었다.
// 지갑을 두면 매 챕터 끝에 진짜 선택이 선다 — **지금 갚아서 이자를 줄일 것인가, 쥐고
// 있다가 생활비로 버틸 것인가.** 갚으면 이자가 줄고, 안 갚으면 다음 챕터를 굶지 않는다.
// 이 게임에서 빚 이자는 챕터 끝에 한 번 붙으므로(`chapters.ts` 의 `interest`),
// **그 직전에 넣은 돈이 가장 값어치가 크다.**
//
// ── 왜 알바로는 절대 못 갚나 ─────────────────────────────────
// 일당 8만, 생활비 하루 2만이다. 1998~2000 을 36턴 내내 알바만 해도 순이익은
// 216만이고 빚은 3,000만이다. **의도한 것이다.** 알바는 버티는 수단이지 벗어나는
// 수단이 아니다 — 벗어나는 길은 여전히 근거를 대고 맞혀 보수를 받는 것 하나뿐이고,
// 알바는 그 자리까지 **살아서 가는** 값이다.
//
// 숫자는 눈대중이 아니라 재서 정했다. `test/game-wallet.test.ts` 의
// 「굶지 않으려면 세 턴에 한 번은 팔아야 한다」와 `test/game-engine.test.ts` 의
// 「빚은 갚을 수 있어야 한다」가 그 셈을 붙잡는다.

/** 1998년 1월 1일의 지갑. 회사가 없어졌고 퇴직금은 안 나왔다. */
export const WALLET_START = 0;

/**
 * 프롤로그의 지갑. **1997년 11월의 나는 아직 월급쟁이다.**
 *
 * 0 으로 두면 프롤로그 넉 턴 내내 생활비를 못 내 급전이 쌓이는데, 그건 이 장의
 * 이야기가 아니다 — 1997 은 **고객 돈**을 잃는 장이고, 내 살림이 무너지는 것은
 * 회사가 없어진 다음이다. 이 돈은 `accountLost` 가 1998 에서 0 으로 지운다.
 */
export const SALARY_LEFT = 500_000;

/**
 * 한 턴(하루)의 생활비. 방세·밥값. **안 내는 선택지는 없다.**
 *
 * 빚 3,000만에 견주면 푼돈이다 — 그게 요점이다. 생활비가 아프게 하는 것은 지갑이
 * 아니라 **에너지**다. 못 내면 알바를 해야 하고, 알바는 근거를 만들 에너지를 먹는다.
 */
export const LIVING_COST = 20_000;

/**
 * 알바 한 번의 일당. **생활비 네 턴치다.**
 *
 * 이 비율이 알바의 빈도를 정한다 — 한 번 팔면 나흘을 산다. 12턴 챕터에 서너 번이고,
 * 나머지 여덟아홉 턴이 영업에 쓸 수 있는 시간이다. 여기를 생활비의 두 배쯤으로
 * 내리면 **알바에 갇힌다**: 번 돈이 그날 생활비로 거의 다 나가 다음 턴에 또 팔아야
 * 하고, 에너지가 말라 넉 턴 만에 소진으로 끝난다. 실제로 그렇게 재 봤다.
 */
export const PARTTIME_PAY = 80_000;

/**
 * 알바 한 번에 드는 에너지. **알아보는 값(3)보다 훨씬 비싸다.**
 *
 * 하루를 통째로 파는 일이라서다. 그리고 이 값이 비싸야 「알바로 연명하며 버틴다」가
 * 공짜 전략이 안 된다 — 알바만 하면 에너지가 말라 보수율이 바닥이 되고, 고객이 맡기는
 * 액수도 같이 준다(`core/clients.ts` 의 `entrustAmount`).
 */
export const PARTTIME_ENERGY = 4;

/**
 * 생활비를 못 냈을 때 대신 지는 빚. **모자란 만큼이 아니라 이 값이 통째로 붙는다.**
 *
 * 최 사장에게서 급전을 당기는 것이라, 2만이 모자라서 2만을 빌리지는 않는다.
 * 생활비 열 턴치다. 못 낸 턴마다 이만큼씩 늘어나고 챕터 끝에 이자까지 먹으므로,
 * 굶는 것이 조용히 넘어가지 않는다.
 */
export const SHORTFALL_DEBT = 200_000;

/* ── 매 턴 일어나는 것 ───────────────────────────────────────── */

export interface LivingResult {
    wallet: number;
    debt: number;
    /** 지갑에서 실제로 나간 돈. */
    paid: number;
    /** 못 내서 빚을 졌는가. */
    short: boolean;
}

/**
 * 한 턴의 생활비를 낸다. **지갑이 모자라면 있는 것까지만 내고 나머지는 빚이 된다.**
 *
 * 지갑은 절대 음수가 되지 않는다 — 마이너스 지갑은 화면에서 빚과 구별이 안 가고,
 * 그러면 돈 갈래가 셋인지 넷인지 알 수 없어진다.
 */
export function payLiving(wallet: number, debt: number, cost: number = LIVING_COST): LivingResult {
    const paid = Math.min(Math.max(0, wallet), cost);
    const short = paid < cost;
    return {
        wallet: wallet - paid,
        debt: short ? debt + SHORTFALL_DEBT : debt,
        paid,
        short,
    };
}

/* ── 갚는다 ─────────────────────────────────────────────────── */

export interface RepayResult {
    wallet: number;
    debt: number;
    /** 실제로 갚은 돈. */
    paid: number;
}

/**
 * 지갑에서 빚으로. **지갑에 있는 것보다, 남은 빚보다 더 갚을 수는 없다.**
 *
 * 화면이 「전부 갚는다」 한 버튼으로 부르든 액수를 받아 부르든 이 함수 하나를 지난다.
 * 셈이 두 군데가 되면 어느 날 한쪽만 바뀐다.
 */
export function repay(wallet: number, debt: number, amount: number): RepayResult {
    const paid = Math.max(0, Math.min(Math.floor(amount), Math.max(0, wallet), Math.max(0, debt)));
    return { wallet: wallet - paid, debt: debt - paid, paid };
}

/** 지금 누를 수 있는 최대 상환액. 버튼의 부제가 이 값을 적는다. */
export function repayable(wallet: number, debt: number): number {
    return Math.max(0, Math.min(Math.floor(wallet), Math.floor(debt)));
}

/* ── 얼마나 버틸 수 있나 ─────────────────────────────────────── */

/**
 * 지금 지갑으로 **생활비를 몇 턴이나 더 낼 수 있는가.** 화면이 이 값을 적는다.
 *
 * 「지갑 8만원」보다 「4턴치」가 결정에 쓰인다 — 챕터가 12턴이므로 이 숫자가
 * 0 이면 이번 턴에 팔아야 한다는 뜻이고, 크면 영업에 쓸 시간이 남았다는 뜻이다.
 */
export function turnsAfloat(wallet: number, cost: number = LIVING_COST): number {
    if (cost <= 0) return Infinity;
    return Math.floor(Math.max(0, wallet) / cost);
}
