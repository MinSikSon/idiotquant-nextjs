export function faqSchema(items: readonly FaqItem[], path: string) {
  return {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    '@id': `https://idiotquant.com${path}#faq`,
    inLanguage: 'ko-KR',
    mainEntity: items.map(({ q, a }) => ({
      '@type': 'Question', name: q,
      acceptedAnswer: { '@type': 'Answer', text: a },
    })),
  };
}
